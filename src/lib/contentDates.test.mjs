import assert from 'node:assert/strict';
import { test } from 'node:test';
import { contentLastmods, dateInfo, normalisePath } from './contentDates.mjs';

test('content dates cover published guides and fall back only where a page has no date of its own', () => {
  const dates = contentLastmods();
  assert.equal(normalisePath('https://archiemiller48.github.io/tried-and-tooled/compare/lovable-vs-bolt/'), '/tried-and-tooled/compare/lovable-vs-bolt/');
  assert.equal(dates.get('/tried-and-tooled/use-cases/research-and-summarise-sources/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/use-cases/translate-a-document/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/use-cases/proofread-and-edit/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/use-cases/design-logos-and-graphics/'), '2026-11-05');
  assert.equal(dates.get('/tried-and-tooled/use-cases/check-if-an-image-is-ai/'), '2026-11-06');
  assert.equal(dates.get('/tried-and-tooled/use-cases/analyse-a-spreadsheet/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/use-cases/write-posts-and-emails/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/use-cases/make-a-slide-deck/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/use-cases/vibe-code-an-mvp/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/compare/coderabbit-vs-greptile/'), '2026-11-02');
  assert.equal(dates.get('/tried-and-tooled/best/ai-app-builders-for-non-coders/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/best/ai-translation-tools/'), '2026-11-04');
  assert.equal(dates.get('/tried-and-tooled/best/ai-tools-for-small-business/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/alternatives/grammarly/'), '2026-11-04');
  assert.equal(dates.get('/tried-and-tooled/tested/'), '2026-11-14');
  assert.equal(dates.get('/tried-and-tooled/newsletter/issue-1/'), '2026-10-19');
  assert.equal(dates.get('/tried-and-tooled/newsletter/issue-3/'), '2026-10-29');
  assert.equal(dates.get('/tried-and-tooled/newsletter/issue-4/'), '2026-11-05');
  assert.equal(dates.get('/tried-and-tooled/newsletter/issue-5/'), '2026-11-12');
  assert.equal(dates.get('/tried-and-tooled/newsletter/'), '2026-11-12');
  assert.ok(dates.get('/tried-and-tooled/'));
  assert.equal(dates.get('/tried-and-tooled/compare/elevenlabs-vs-descript/'), '2026-11-10');
  assert.equal(dates.get('/tried-and-tooled/best/ai-product-background-removers/'), '2026-11-09');
  assert.equal(dates.get('/tried-and-tooled/compare/'), '2026-11-10');
  const about = dateInfo('/about/');
  assert.equal(about.aggregated, true);
  assert.ok(about.date);
  const compare = dateInfo('/compare/lovable-vs-bolt/');
  assert.equal(compare.aggregated, false);
  assert.equal(compare.date, '2026-11-09');
});
